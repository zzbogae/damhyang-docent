def memo_sentence(rng: random.Random) -> str:
    r = rng.random()
    if r < 0.35:
        return rng.choice(BASE_NOTES)
    if r < 0.5:
        p, o = rng.choice(PLACES), rng.choice(OBJECTS)
        return f"{p}에서 {josa(o, '을', '를')} 봤다 {rng.choice(THOUGHTS)}"
    if r < 0.6:
        f = rng.choice(FOODS)
        return f"{josa(f, '을', '를')} 먹었다 {rng.choice(['맛있었다', '짰다', '좀 싱거웠다', '다음엔 덜 맵게', '또 먹고 싶다'])}"
    if r < 0.7:
        return f"아이디어. {rng.choice(IDEAS)}"
    if r < 0.78:
        return f"할 일: {rng.choice(TODOS)}, {rng.choice(TODOS)}"
    if r < 0.84:
        return f"읽을 것 「{rng.choice(BOOKS)}」"
    if r < 0.92:
        p = rng.choice(PLACES)
        return f"{josa(p, '은', '는')} {rng.choice(['오늘따라 붐볐다', '생각보다 조용했다', '공사 중이었다', '불이 일찍 꺼졌다', '새로 칠해져 있었다'])}"
    o = rng.choice(OBJECTS)
    return f"{josa(o, '이', '가')} {rng.choice(['한참 그 자리에 있었다', '어제와 다른 곳에 있었다', '햇빛을 받고 있었다', '비에 젖어 있었다'])}"


def memo_text(rng: random.Random, n_sentences: int, hard: bool = False) -> str:
    parts = []
    for _ in range(n_sentences):
        if hard and rng.random() < 0.55:
            parts.append(rng.choice(HARD_NOTES))
        else:
            parts.append(memo_sentence(rng))
    sep = rng.choice([". ", "\n", " / "]) if n_sentences > 1 else ""
    return sep.join(parts)


