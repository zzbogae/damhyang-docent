def kakao_mine(rng: random.Random, p_first: float, p_assert: float) -> str:
    r = rng.random()
    if r < p_first * p_assert * 2:
        text = rng.choice(KAKAO_BOTH)
    elif r < p_first:
        text = rng.choice(KAKAO_FIRST)
    elif r < p_first + p_assert:
        text = rng.choice(KAKAO_ASSERT)
    else:
        text = rng.choice(KAKAO_NEUTRAL)
    if rng.random() < 0.04:
        text = text + "\n" + rng.choice(KAKAO_NEUTRAL)
    return text


def kakao_other(rng: random.Random) -> str:
    return rng.choice(KAKAO_OTHER + KAKAO_NEUTRAL)


