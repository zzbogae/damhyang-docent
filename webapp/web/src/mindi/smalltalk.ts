/** 기록을 묻는 말(언제·어느 주·몇 번…)은 여기서 받지 않고 intent.ts로 넘긴다 */
const RECORD_Q = /(언제|어느\s?주|몇\s?(번|개|장|주)|얼마나|그\s?주|지난\s?주|작년|올해|이번\s?주|\d{4}년|\d{1,2}월)/;

export function smallTalkCategory(raw: string): Cat | null {
  const t = raw.normalize('NFC').trim();
  if (!t || RECORD_Q.test(t)) return null;
  return CATS.find(([, re]) => re.test(t))?.[0] ?? null;
}

// 사용자가 쓴 말을 그대로 되돌려 주기 위해, 맞은 말의 가장 가까운 어절을 꺼낸다(「요즘 너무 불안해요」 → 「불안해요」)
function quoteOf(raw: string, cat: Cat): string {
  const re = CATS.find(([c]) => c === cat)![1];
  const t = raw.normalize('NFC').trim();
  const m = re.exec(t);
  if (!m) return '';
  const words = t.split(/\s+/);
  const w = words.find((x) => x.includes(m[0])) ?? m[0];
  return w.replace(/[.!?~,ㅠㅜ…]+$/g, '');
}

