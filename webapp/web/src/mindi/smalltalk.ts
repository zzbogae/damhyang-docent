const hash = (s: string) => [...s].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7);

function fill(line: string, quote: string, name?: string): string | null {
  let s = line.replaceAll('{말}', quote || '그 말');
  if (name) return s.replaceAll('{이름}', name);
  if (!s.includes('{이름}')) return s;
  const kept = s.split('\n')
    .map((l) => l.split(/(?<=[.?!])\s+/).filter((sent) => !sent.includes('{이름}')).join(' '))
    .filter((l) => l.trim());
  s = kept.join('\n').trim();
  return s || null;
}

/**
 * 일상 대화·마음 공감 답. 받을 말이 아니면 null.
 * 진단·치료·위기(talk.fixedKind)와 대본집 공감(talk.scriptedReply)이 먼저이고, 기록을 묻는 말은 intent.ts가 받는다.
 */
export function smallTalk(raw: string, voice: Voice, name?: string): string | null {
  const cat = smallTalkCategory(raw);
  if (!cat) return null;
  const quote = quoteOf(raw, cat);
  const level = intensity(raw);
  const isFeel = cat in FEEL;
  const rows = isFeel ? FEEL[cat as keyof typeof FEEL] : TALK[cat as keyof typeof TALK];
  const row = rows[hash(raw.normalize('NFC')) % rows.length];
  const main = fill(row[voice], quote, name);
  if (!main) return null;
  const heavy = isFeel && !['glad', 'okay'].includes(cat);
  const parts = [main];
  if (heavy && level >= 2) parts.unshift(SLOW[voice]);
  if (heavy && level >= 1) parts.push(OFFER[voice]);
  return parts.join('\n');
}
