/** 말의 세기: 0 차분 · 1 조금 · 2 많이. 어떤 감정인지가 아니라 「얼마나 세게 말했나」만 본다 */
export function intensity(raw: string): 0 | 1 | 2 {
  const t = raw.normalize('NFC');
  let n = 0;
  n += Math.min(2, (t.match(/[ㅠㅜ]{2,}/g) ?? []).length);
  n += Math.min(2, (t.match(/[!?]{2,}|[.…]{3,}/g) ?? []).length);
  n += Math.min(3, (t.match(/(너무|진짜|정말|계속|맨날|매일|자꾸|하나도|아무것도|전부|다\s|미치|죽겠|못\s?하겠|못하겠|모르겠|안\s?돼|어떡)/g) ?? []).length);
  if (t.length > 60) n += 1;
  return n >= 4 ? 2 : n >= 2 ? 1 : 0;
}

